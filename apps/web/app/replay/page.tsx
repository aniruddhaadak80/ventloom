import { SECONDS_PER_DAY, unrestIndex, unrestIndicators } from "@repo/core";
import { findVolcano, VOLCANO_CATALOGUE } from "@repo/seed";
import { Panel, Sparkline, Stat, StatGrid } from "@repo/ui";
import type { Metadata } from "next";
import { ObservatoryNav } from "../../components/observatory-nav";
import { describeEpoch, MAX_EPOCH_S, readEpoch } from "../../lib/epoch";

export const metadata: Metadata = {
  title: "Replay â€” the deterministic time machine",
  description:
    "Scrub any epoch of the seeded world. The observatory is a pure function of the epoch, so the same URL always renders the same state.",
};

/** How many days the history trail covers. */
const TRAIL_DAYS = 60;
const TRAIL_STEP_DAYS = 1;

export default function ReplayPage({
  searchParams,
}: {
  searchParams: Record<string, string | undefined>;
}) {
  const { epochS, timestampIso } = readEpoch(searchParams);
  const requested = searchParams.volcano ?? "kilauea";
  const volcano = findVolcano(requested) ?? findVolcano("kilauea");
  if (!volcano) throw new Error("volcano catalogue is empty");

  // The trail is generated by walking backwards from the current epoch. It is
  // the same function the "now" view calls, just at many epochs, which is what
  // makes scrubbing honest rather than a re-roll.
  const start = Math.max(0, epochS - TRAIL_DAYS * SECONDS_PER_DAY);
  const trail: { epochS: number; unrest: number; rsam: number; inflation: number }[] = [];
  for (let day = start; day <= epochS; day += TRAIL_STEP_DAYS * SECONDS_PER_DAY) {
    trail.push({
      epochS: day,
      unrest: unrestIndex(volcano, day),
      rsam: unrestIndicators(volcano, day).rsamRatio,
      inflation: unrestIndicators(volcano, day).sourceVolumeChangeM3,
    });
  }
  const current = unrestIndicators(volcano, epochS);

  return (
    <main id="main" className="mx-auto max-w-7xl px-4 py-6 sm:px-6">
      <header className="mb-6 flex flex-col gap-3">
        <div className="flex flex-wrap items-end justify-between gap-3">
          <div>
            <p className="font-[family-name:var(--font-mono)] text-[11px] uppercase tracking-[0.2em] text-[var(--color-lava)]">
              replay
            </p>
            <h1 className="mt-1 font-[family-name:var(--font-display)] text-2xl tracking-tight sm:text-3xl">
              The deterministic time machine
            </h1>
            <p className="mt-2 max-w-2xl text-sm leading-relaxed text-[var(--color-ash-muted)]">
              ventloom has no clock. The observatory at epoch <em>t</em> is a function of <em>t</em>{" "}
              and nothing else, so scrubbing backwards shows exactly what the instrument would have
              recorded rather than a fresh roll of the dice. Pick an epoch and every surface in the
              app follows.
            </p>
          </div>
          <ObservatoryNav epoch={epochS} />
        </div>
        <p className="font-[family-name:var(--font-mono)] text-xs text-[var(--color-ash-dim)]">
          {volcano.name} Â· {timestampIso} Â· {describeEpoch(epochS)}
        </p>
      </header>

      <Panel
        title="Scrub the epoch"
        subtitle="The URL is the state. Bookmark any epoch and it renders identically."
      >
        <form method="get" className="flex flex-wrap items-end gap-4">
          <input type="hidden" name="volcano" value={volcano.id} />
          <label className="text-xs text-[var(--color-ash-dim)]">
            Epoch (seconds from 2026-01-01, 0 to {MAX_EPOCH_S.toLocaleString("en-US")})
            <input
              type="number"
              name="epoch"
              defaultValue={epochS}
              min={0}
              max={MAX_EPOCH_S}
              step={SECONDS_PER_DAY}
              className="mt-1 block w-48 rounded-[var(--radius-sm)] border border-[var(--color-slag)] bg-[var(--color-abyss)] px-2 py-1.5 font-[family-name:var(--font-mono)] text-xs text-[var(--color-ash)]"
            />
          </label>
          <button
            type="submit"
            className="rounded-[var(--radius-sm)] bg-[var(--color-lava)] px-3 py-1.5 font-[family-name:var(--font-display)] text-xs text-[var(--color-abyss)]"
          >
            Render epoch
          </button>
        </form>
      </Panel>

      <div className="mt-4 grid gap-4 lg:grid-cols-3">
        <Panel
          title="Unrest, last 60 days"
          subtitle="A sum of incommensurate sinusoids plus the profile trend."
        >
          <div className="h-24">
            <Sparkline
              values={trail.map((t) => t.unrest)}
              tone="lava"
              label="Unrest over the last 60 days"
            />
          </div>
          <p className="mt-2 font-[family-name:var(--font-mono)] text-xs tabular-nums text-[var(--color-lava)]">
            now {unrestIndex(volcano, epochS).toFixed(4)}
          </p>
        </Panel>
        <Panel
          title="RSAM ratio, last 60 days"
          subtitle="Amplitude relative to the 30-day background."
        >
          <div className="h-24">
            <Sparkline
              values={trail.map((t) => t.rsam)}
              tone="seismic"
              label="RSAM ratio over the last 60 days"
            />
          </div>
          <p className="mt-2 font-[family-name:var(--font-mono)] text-xs tabular-nums text-[var(--color-seismic)]">
            now {current.rsamRatio.toFixed(2)}Ã-
          </p>
        </Panel>
        <Panel title="Source volume, last 60 days" subtitle="Negative is deflation.">
          <div className="h-24">
            <Sparkline
              values={trail.map((t) => t.inflation)}
              tone="ash"
              label="Source volume over the last 60 days"
            />
          </div>
          <p className="mt-2 font-[family-name:var(--font-mono)] text-xs tabular-nums text-[var(--color-ash-muted)]">
            now {(current.sourceVolumeChangeM3 / 1e6).toFixed(2)} MmÂ³
          </p>
        </Panel>
      </div>

      <div className="mt-4 grid gap-4 lg:grid-cols-2">
        <Panel
          title="Why determinism here and not a replay log"
          subtitle="The usual approach and why it fails."
        >
          <p className="text-xs leading-relaxed text-[var(--color-ash-muted)]">
            A replay console normally writes a log and plays it back. ventloom does not, because a
            log is a second source of truth that can drift from the live state and cannot be
            scrubbed past its own start. Deriving the past from the same function that produces the
            present means there is no log to go stale, no storage to bound, and any epoch in the
            seeded year is reachable, including ones the UI never showed.
          </p>
          <StatGrid columns={2}>
            <Stat label="Trail length" value={`${trail.length} days`} />
            <Stat
              label="Reachable range"
              value={`${Math.floor(MAX_EPOCH_S / SECONDS_PER_DAY)} days`}
            />
          </StatGrid>
        </Panel>

        <Panel
          title="Every volcano at this epoch"
          subtitle="The same clock, twelve different worlds."
        >
          <ul className="divide-y divide-[var(--color-slag)]/70">
            {VOLCANO_CATALOGUE.map((v) => {
              const indicators = unrestIndicators(v, epochS);
              return (
                <li key={v.id} className="grid grid-cols-[1fr_auto] items-center gap-2 py-2">
                  <a
                    href={`/replay?epoch=${epochS}&volcano=${v.id}`}
                    className="text-xs text-[var(--color-ash-muted)] hover:text-[var(--color-lava)]"
                  >
                    {v.name}
                  </a>
                  <span className="font-[family-name:var(--font-mono)] text-[11px] tabular-nums text-[var(--color-ash-dim)]">
                    u {unrestIndex(v, epochS).toFixed(3)} Â· rsam {indicators.rsamRatio.toFixed(2)}
                    Ã-
                  </span>
                </li>
              );
            })}
          </ul>
        </Panel>
      </div>
    </main>
  );
}
